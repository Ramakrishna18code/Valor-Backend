ALTER TABLE technician_profiles ADD COLUMN public_name VARCHAR(160) NULL;
CREATE TABLE service_team_members (
 id BIGINT AUTO_INCREMENT PRIMARY KEY,
 service_request_id BIGINT NOT NULL,
 lead_technician_profile_id BIGINT NOT NULL,
 helper_technician_profile_id BIGINT NOT NULL,
 customer_display_name VARCHAR(160) NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'REQUESTED',
 request_reason VARCHAR(1000) NOT NULL,
 decision_reason VARCHAR(1000) NULL,
 requested_by_user_id BIGINT NOT NULL,
 approved_by_user_id BIGINT NULL,
 requested_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 decided_at DATETIME(6) NULL,
 CONSTRAINT uk_service_team_helper UNIQUE(service_request_id,helper_technician_profile_id),
 CONSTRAINT fk_stm_request FOREIGN KEY(service_request_id) REFERENCES service_requests(id),
 CONSTRAINT fk_stm_lead FOREIGN KEY(lead_technician_profile_id) REFERENCES technician_profiles(id),
 CONSTRAINT fk_stm_helper FOREIGN KEY(helper_technician_profile_id) REFERENCES technician_profiles(id),
 CONSTRAINT fk_stm_requester FOREIGN KEY(requested_by_user_id) REFERENCES users(id),
 CONSTRAINT fk_stm_approver FOREIGN KEY(approved_by_user_id) REFERENCES users(id),
 CONSTRAINT ck_stm_status CHECK(status IN ('REQUESTED','APPROVED','REJECTED','REMOVED')),
 CONSTRAINT ck_stm_distinct CHECK(lead_technician_profile_id<>helper_technician_profile_id)
);
CREATE TABLE service_helper_work_logs (
 id BIGINT AUTO_INCREMENT PRIMARY KEY,
 team_member_id BIGINT NOT NULL,
 work_date DATE NOT NULL,
 minutes_worked INT NOT NULL,
 description VARCHAR(1000) NOT NULL,
 submitted_by_user_id BIGINT NOT NULL,
 reviewed_by_user_id BIGINT NULL,
 reviewed_at DATETIME(6) NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'SUBMITTED',
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 CONSTRAINT fk_shwl_member FOREIGN KEY(team_member_id) REFERENCES service_team_members(id),
 CONSTRAINT fk_shwl_submitter FOREIGN KEY(submitted_by_user_id) REFERENCES users(id),
 CONSTRAINT fk_shwl_reviewer FOREIGN KEY(reviewed_by_user_id) REFERENCES users(id),
 CONSTRAINT ck_shwl_minutes CHECK(minutes_worked>0 AND minutes_worked<=1440),
 CONSTRAINT ck_shwl_status CHECK(status IN ('SUBMITTED','APPROVED','REJECTED'))
);
CREATE TABLE service_helper_allowances (
 id BIGINT AUTO_INCREMENT PRIMARY KEY,
 team_member_id BIGINT NOT NULL UNIQUE,
 basis VARCHAR(12) NOT NULL,
 units INT NOT NULL,
 rate_snapshot DECIMAL(12,2) NOT NULL,
 amount DECIMAL(12,2) NOT NULL,
 currency VARCHAR(3) NOT NULL DEFAULT 'INR',
 status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
 reason VARCHAR(1000) NOT NULL,
 approved_by_user_id BIGINT NULL,
 approved_at DATETIME(6) NULL,
 paid_by_user_id BIGINT NULL,
 paid_at DATETIME(6) NULL,
 transfer_reference VARCHAR(120) NULL UNIQUE,
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 CONSTRAINT fk_sha_member FOREIGN KEY(team_member_id) REFERENCES service_team_members(id),
 CONSTRAINT fk_sha_approver FOREIGN KEY(approved_by_user_id) REFERENCES users(id),
 CONSTRAINT fk_sha_payer FOREIGN KEY(paid_by_user_id) REFERENCES users(id),
 CONSTRAINT ck_sha_basis CHECK(basis IN ('JOB','DAY')),
 CONSTRAINT ck_sha_units CHECK(units>0),
 CONSTRAINT ck_sha_amount CHECK(rate_snapshot>0 AND amount=rate_snapshot*units),
 CONSTRAINT ck_sha_status CHECK(status IN ('DRAFT','APPROVED','PAID','HELD'))
);
